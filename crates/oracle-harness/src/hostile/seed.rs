//! The seed corpus: the review findings the library was built from, each
//! mapped to the dimension that generates its input and to what became of it.
//!
//! An audit of codex review logs (2026-11-19) classified every finding; two
//! hundred needed a contrived input. [`SEED`] is those findings. The claim
//! "the library covers what review found" is this table: a finding either
//! names the [`Dimension`] whose values include its input, or says why no
//! dimension does ([`NoDimension`]), and its [`Outcome`] says how that was
//! shown. The tests here hold the table to the library (every dimension named
//! exists) and to the workspace (a finding said to be on main cites a file
//! that is).
//!
//! The acceptance test of the library is that no row is left
//! [`Outcome::Pending`]: each finding on main is reproduced by a generated
//! case when its fix is reverted, or declined by its subject, or out of
//! scope with the reason. A row moves there when the harness for its
//! boundary draws its dimension.

use std::collections::BTreeMap;

use super::Dimension;

/// The table, as checked in.
pub const SEED: &str = include_str!("seed.tsv");

/// Why a finding's input belongs to no dimension.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum NoDimension {
    /// The input is the *shape of a referenced assembly*: declarations or
    /// metadata rows built to collide (an internal `[<Extension>]`
    /// abbreviation in a friend assembly, a cyclic `NestedClass` table). The
    /// retrofit of the sema and assembly harnesses adds the kind, whose
    /// values are assemblies and not text.
    AssemblyShape,
    /// The input is build logic in the project: a target, a task parameter
    /// or a tool wrapper that changes what the build does without changing
    /// any value the evaluation reads. The oracle that runs real builds is
    /// what meets these, and its fixture domain is closed against them.
    BuildLogic,
    /// The input is a well-formed request that the oracle must refuse for
    /// what it asks (a graph edge outside the closure, a reference left
    /// out). Each oracle's own table of refusals lists these; there is no
    /// value to draw.
    RequestSemantics,
    /// The defect is in one harness's own fixture or bookkeeping, and no
    /// input value triggers it.
    FixtureLogic,
    /// The input is a file beside the project that the build's command line
    /// reads (`Directory.Build.rsp`, `MSBuild.rsp`): a route the evaluation
    /// does not see.
    CommandLineFile,
    /// The input is the structure of a project document (metadata named as a
    /// reserved element, a project writing a name a tool writes), which the
    /// generators of project documents own.
    DocumentStructure,
    /// The input is an F# program of some shape, which each harness's own
    /// generator of programs owns.
    ProgramShape,
    /// The input is a restore gone stale against its project, which the
    /// restore boundary's own differential owns.
    RestoreStaleness,
}

impl NoDimension {
    /// Every reason.
    pub const ALL: &'static [NoDimension] = &[
        NoDimension::AssemblyShape,
        NoDimension::BuildLogic,
        NoDimension::RequestSemantics,
        NoDimension::FixtureLogic,
        NoDimension::CommandLineFile,
        NoDimension::DocumentStructure,
        NoDimension::ProgramShape,
        NoDimension::RestoreStaleness,
    ];

    /// The reason's name in the table.
    pub fn id(self) -> &'static str {
        match self {
            NoDimension::AssemblyShape => "assembly-shape",
            NoDimension::BuildLogic => "build-logic",
            NoDimension::RequestSemantics => "request-semantics",
            NoDimension::FixtureLogic => "fixture-logic",
            NoDimension::CommandLineFile => "command-line-file",
            NoDimension::DocumentStructure => "document-structure",
            NoDimension::ProgramShape => "program-shape",
            NoDimension::RestoreStaleness => "restore-staleness",
        }
    }
}

/// What generates a finding's input.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Generates {
    /// This dimension.
    Dimension(Dimension),
    /// No dimension, for this reason.
    Nothing(NoDimension),
}

/// What became of a finding.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Outcome {
    /// A case generated by this census fails when the finding's fix is
    /// reverted.
    Reproduces(String),
    /// The subject declines the case this census generates.
    Declines(String),
    /// Out of scope, for this reason.
    OutOfScope(String),
    /// On main, and no harness draws the dimension yet.
    Pending,
    /// The code the finding is about is on this branch, not yet merged.
    Branch(String),
}

/// One finding.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Finding {
    /// The audit's name for it: the model, the log, the position.
    pub id: String,
    /// The file it cites, if the audit recorded one.
    pub file: Option<String>,
    /// What generates its input.
    pub generates: Generates,
    /// What became of it.
    pub outcome: Outcome,
    /// Its title.
    pub title: String,
}

/// Read a seed table: `id<TAB>where<TAB>dimension<TAB>outcome<TAB>title`,
/// sorted by id, with `#` comment lines.
///
/// # Errors
///
/// The first malformed line, with its number.
pub fn parse(table: &str) -> Result<Vec<Finding>, String> {
    let mut findings: Vec<Finding> = Vec::new();
    for (i, line) in table.lines().enumerate() {
        let bad = |why: &str| format!("line {}: {why}: {line:?}", i + 1);
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let fields: Vec<&str> = line.split('\t').collect();
        let [id, file, dimension, outcome, title] = fields[..] else {
            return Err(bad("a row is id, where, dimension, outcome and title"));
        };
        let generates = match dimension.strip_prefix("none: ") {
            Some(reason) => Generates::Nothing(
                NoDimension::ALL
                    .iter()
                    .copied()
                    .find(|n| n.id() == reason)
                    .ok_or_else(|| bad("no such reason for having no dimension"))?,
            ),
            None => Generates::Dimension(
                Dimension::from_key(dimension).ok_or_else(|| bad("no such dimension"))?,
            ),
        };
        let detail = |prefix: &str| {
            outcome
                .strip_prefix(prefix)
                .filter(|rest| !rest.trim().is_empty())
                .map(str::to_owned)
        };
        let outcome = if outcome == "pending" {
            Outcome::Pending
        } else if let Some(census) = detail("reproduces: ") {
            Outcome::Reproduces(census)
        } else if let Some(census) = detail("declines: ") {
            Outcome::Declines(census)
        } else if let Some(why) = detail("out-of-scope: ") {
            Outcome::OutOfScope(why)
        } else if let Some(branch) = detail("branch: ") {
            Outcome::Branch(branch)
        } else {
            return Err(bad("no such outcome"));
        };
        if matches!(
            (&generates, &outcome),
            (
                Generates::Nothing(_),
                Outcome::Reproduces(_) | Outcome::Declines(_)
            )
        ) {
            return Err(bad(
                "a finding no dimension generates cannot have been generated",
            ));
        }
        if title.trim().is_empty() {
            return Err(bad("a finding has a title"));
        }
        if let Some(previous) = findings.last()
            && previous.id.as_str() >= id
        {
            return Err(bad("rows are sorted by id, each id once"));
        }
        findings.push(Finding {
            id: id.to_owned(),
            file: (file != "-").then(|| file.to_owned()),
            generates,
            outcome,
            title: title.to_owned(),
        });
    }
    Ok(findings)
}

/// How many findings each dimension (or reason for none) generates, for a
/// report.
pub fn tally(findings: &[Finding]) -> BTreeMap<String, usize> {
    let mut out = BTreeMap::new();
    for finding in findings {
        let key = match finding.generates {
            Generates::Dimension(d) => d.key(),
            Generates::Nothing(n) => format!("none: {}", n.id()),
        };
        *out.entry(key).or_default() += 1;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::hostile::coverage;

    #[test]
    fn the_seed_table_is_well_formed_and_names_only_real_dimensions() {
        let findings = parse(SEED).unwrap_or_else(|e| panic!("seed.tsv: {e}"));
        assert_eq!(findings.len(), 200, "the audit's contrived-input findings");
        let generated = findings
            .iter()
            .filter(|f| matches!(f.generates, Generates::Dimension(_)))
            .count();
        eprintln!(
            "hostile seed corpus: {generated} of {} findings are generated by a dimension",
            findings.len()
        );
        for (key, n) in tally(&findings) {
            eprintln!("  {key}: {n}");
        }
        // The library was built from these findings: most of them must be
        // inputs it can generate, or the table is a list of excuses.
        assert!(generated * 5 >= findings.len() * 3, "{generated}");
    }

    /// A finding said to be on main cites a file that is on main, so a row
    /// cannot stay `pending` (or claim an outcome) for code that is elsewhere.
    #[test]
    fn a_finding_on_main_cites_a_file_on_main() {
        let workspace = coverage::workspace();
        for finding in parse(SEED).unwrap() {
            let on_main = !matches!(finding.outcome, Outcome::Branch(_));
            if let (true, Some(file)) = (on_main, &finding.file) {
                assert!(
                    workspace.join(file).is_file(),
                    "{} is {:?} and cites {file}, which is not in this checkout",
                    finding.id,
                    finding.outcome
                );
            }
        }
    }

    /// An outcome that names a census names one the coverage table declares,
    /// drawing the finding's dimension.
    #[test]
    fn an_outcome_names_a_census_that_draws_the_dimension() {
        let rows = coverage::parse(coverage::BOUNDARIES).unwrap();
        for finding in parse(SEED).unwrap() {
            let (Outcome::Reproduces(census) | Outcome::Declines(census)) = &finding.outcome else {
                continue;
            };
            let Generates::Dimension(dimension) = finding.generates else {
                unreachable!("refused by `parse`")
            };
            let drawn = rows.iter().any(|row| match &row.status {
                coverage::Status::Draws(censuses) => censuses
                    .iter()
                    .any(|c| c.census == *census && c.kinds.contains(&dimension.kind())),
                _ => false,
            });
            assert!(
                drawn,
                "{}: no census {census:?} in boundaries.tsv draws {}",
                finding.id,
                dimension.kind()
            );
        }
    }

    #[test]
    fn malformed_seed_tables_are_refused() {
        for (table, why) in [
            ("a\tb\tc\n", "a row is"),
            ("a\t-\tname.nonsense\tpending\tt\n", "no such dimension"),
            ("a\t-\tnone: because\tpending\tt\n", "no such reason"),
            ("a\t-\tfs.fifo\tdone\tt\n", "no such outcome"),
            ("a\t-\tfs.fifo\tbranch: \tt\n", "no such outcome"),
            (
                "a\t-\tnone: build-logic\tdeclines: x\tt\n",
                "cannot have been generated",
            ),
            ("a\t-\tfs.fifo\tpending\t \n", "has a title"),
            (
                "b\t-\tfs.fifo\tpending\tt\na\t-\tfs.fifo\tpending\tt\n",
                "sorted by id",
            ),
        ] {
            let error = parse(table).unwrap_err();
            assert!(error.contains(why), "{table:?}: {error}");
        }
        let ok =
            parse("a\tx.rs\tfs.fifo\tdeclines: demo\tt\nb\t-\tnone: build-logic\tpending\tt\n");
        let ok = ok.unwrap();
        assert_eq!(ok[0].outcome, Outcome::Declines("demo".into()));
        assert_eq!(ok[0].file.as_deref(), Some("x.rs"));
        assert_eq!(ok[1].generates, Generates::Nothing(NoDimension::BuildLogic));
    }
}
